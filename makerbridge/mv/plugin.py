def _check_aliases(source: str, log) -> None:
    """Every hook keeps the original in a "var _name"; the plugin is one
    function scope, so a name used twice makes the first hook call itself
    forever ("Maximum call stack size exceeded" in the game)."""
    seen: dict[str, int] = {}
    for number, line in enumerate(source.splitlines(), 1):
        for name in re.findall(r"\bvar (_[A-Za-z0-9_$]+) =", line):
            if name in seen:
                log.error("RM2kCompat.js: %s is declared twice (lines %d and %d); "
                          "the first hook would call itself", name, seen[name], number)
            seen[name] = number


def write(target: str, log, history: int = 40, data: dict | None = None) -> None:
    scale_x = MV_SCREEN[0] / RM2K_SCREEN[0]
    scale_y = MV_SCREEN[1] / RM2K_SCREEN[1]
    plugin_dir = os.path.join(target, "js", "plugins")
    os.makedirs(plugin_dir, exist_ok=True)

    source = TEMPLATE.format(name=PLUGIN_NAME,
                             data=json.dumps(data or {}, ensure_ascii=False),
                             scale_x=round(scale_x, 4),
                             scale_y=round(scale_y, 4),
                             pictures=PICTURES_JS, battle=BATTLE_JS)
    _check_aliases(source, log)
    with open(os.path.join(plugin_dir, f"{PLUGIN_NAME}.js"), "w",
              encoding="utf-8") as fh:
        fh.write(source)
    log.info("wrote js/plugins/%s.js (picture scale %.2f x %.2f)",
             PLUGIN_NAME, scale_x, scale_y)

    with open(os.path.join(plugin_dir, f"{DEBUG_NAME}.js"), "w",
              encoding="utf-8") as fh:
        fh.write(DEBUG_TEMPLATE.format(name=DEBUG_NAME, log=ERROR_LOG,
                                       history=history))
    log.info("wrote js/plugins/%s.js (crashes go to %s next to the game)",
             DEBUG_NAME, ERROR_LOG)

    _register(target, log)


def _register(target: str, log) -> None:
    """Add the plugins to js/plugins.js, a JS file holding a JSON list."""
    path = os.path.join(target, "js", "plugins.js")
    entries = [
        {"name": PLUGIN_NAME, "status": True,
         "description": "RM2k coordinate and command compatibility",
         "parameters": {}},
        {"name": DEBUG_NAME, "status": True,
         "description": "writes crashes and the commands before them to a log",
         "parameters": {}},
    ]
    plugins: list = []
    if os.path.isfile(path):
        try:
            text = open(path, encoding="utf-8").read()
            match = re.search(r"\[.*\]", text, re.S)
            if match:
                plugins = json.loads(match.group(0))
        except (OSError, ValueError) as exc:
            log.warning("could not read js/plugins.js (%s); writing a fresh one", exc)
            plugins = []
    ours = {entry["name"] for entry in entries}
    plugins = [p for p in plugins if p.get("name") not in ours]
    plugins.extend(entries)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("// Generated by RPG Maker.\n// Do not edit this file directly.\n")
        fh.write("var $plugins =\n")
        json.dump(plugins, fh, indent=4, ensure_ascii=False)
        fh.write(";\n")
    log.info("registered %s and %s in js/plugins.js (%d plugin(s) total)",
             PLUGIN_NAME, DEBUG_NAME, len(plugins))
